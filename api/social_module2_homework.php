    $rows = [];
    foreach ($items as $i => $item) $rows[] = ($i + 1) . ') ' . $item;
    return implode("\n\n", $rows);
  };

  $explained = static function (array $items): string {
    $rows = [];
    foreach ($items as $i => $item) $rows[] = '**' . ($i + 1) . ')** ' . $item;
    return implode("\n\n", $rows);
  };

