      $digits = str_split($value);
      return [$value, implode(' ', $digits), implode(',', $digits), implode(';', $digits)];
    };
    $answers = $variants($answer);
    foreach ($extra as $value) $answers = array_merge($answers, $variants($value));
    return array_values(array_unique($answers));
