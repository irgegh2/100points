function english_september_15_present_simple_homework_seed(PDO $pdo): array {
  $lessons = $pdo->query("SELECT l.id FROM lessons l JOIN blocks b ON b.id=l.block_id
    JOIN months m ON m.id=b.month_id JOIN courses c ON c.id=b.course_id JOIN subjects s ON s.id=c.subject_id
    WHERE s.slug='english' AND c.title='Годовой курс ЕГЭ по английскому языку' AND c.type='Основные'
      AND m.name='БЛОК 1' AND b.n=1 AND b.title='Грамматика: времена группы Present'
      AND l.title='Present Simple' AND l.air_at='2026-09-15 18:00'")->fetchAll(PDO::FETCH_COLUMN);
  if (count($lessons) !== 1) throw new RuntimeException('Present Simple: точный урок не найден однозначно');
  $packs = english_september_15_present_simple_homework_packs();
  if (array_map(static fn($p) => count($p['questions']), $packs) !== [25,26,47]) throw new RuntimeException('Неверное число вопросов');
  $json = static fn($v) => $v === null ? null : json_encode($v, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
  $ids = [];
  $pdo->beginTransaction();
  try {
    foreach ($packs as $pack) {
      $find = $pdo->prepare('SELECT * FROM homeworks WHERE lesson_id=? AND title=? ORDER BY id');
      $find->execute([(int)$lessons[0],$pack['title']]);
      $existing = $find->fetchAll();
      if (count($existing) > 1) throw new RuntimeException('Дубли ДЗ: ' . $pack['title']);
      if ($existing) {
        $hw = $existing[0];
        if ($hw['level'] !== $pack['level']) throw new RuntimeException('Уровень ДЗ изменён вручную');
        $qs = $pdo->prepare('SELECT * FROM questions WHERE homework_id=? ORDER BY position,id');
        $qs->execute([(int)$hw['id']]);
        $rows = $qs->fetchAll();
        if (count($rows) !== count($pack['questions'])) throw new RuntimeException('ДЗ уже существует с другим числом вопросов');
        foreach ($pack['questions'] as $i=>$q) {
          $r=$rows[$i];
          foreach (['type','text','solution','hint','points','grade_mode','file_limit'] as $field) {
            if ((string)$r[$field] !== (string)$q[$field]) throw new RuntimeException('Вопрос изменён вручную: ' . ($i+1));
          }
          foreach (['options','correct'] as $field) {
            if (($r[$field]===null ? null : json_decode($r[$field],true)) !== $q[$field]) throw new RuntimeException('Ключ или варианты изменены вручную');
          }
          if ((int)$r['position']!==$i || (int)$r['optional']!==0 || (int)$r['hard']!==0 || (int)$r['case_sensitive']!==0) throw new RuntimeException('Параметры вопроса изменены вручную');
        }
        // Никаких UPDATE: существующие работы, сдачи и ручные дедлайны сохраняются.
        $ids[]=(int)$hw['id'];
        continue;
      }
      $pos=$pdo->prepare('SELECT COALESCE(MAX(position),-1)+1 FROM homeworks WHERE lesson_id=?');
      $pos->execute([(int)$lessons[0]]);
      $pdo->prepare('INSERT INTO homeworks(lesson_id,level,title,deadline,position) VALUES(?,?,?,?,?)')
        ->execute([(int)$lessons[0],$pack['level'],$pack['title'],'2026-09-23 23:59:00',(int)$pos->fetchColumn()]);
      $id=(int)$pdo->lastInsertId();$ids[]=$id;
      $ins=$pdo->prepare('INSERT INTO questions(homework_id,type,text,options,correct,solution,hint,points,optional,hard,case_sensitive,grade_mode,file_limit,position) VALUES(?,?,?,?,?,?,?,?,0,0,0,?,?,?)');
      foreach ($pack['questions'] as $i=>$q) $ins->execute([$id,$q['type'],$q['text'],$json($q['options']),$json($q['correct']),$q['solution'],$q['hint'],$q['points'],$q['grade_mode'],$q['file_limit'],$i]);
    }
    $pdo->commit();return $ids;
  } catch (Throwable $e) {
    if ($pdo->inTransaction()) $pdo->rollBack();
    throw $e;
  }
