    $digits = str_split($answer);
    return array_values(array_unique([
      $answer,
      implode(' ', $digits),
      implode(',', $digits),
      implode(';', $digits),
    ]));
  };

  $numbered = static function (array $items): string {
    $rows = [];
    foreach ($items as $index => $item) $rows[] = ($index + 1) . ') ' . $item;
    return implode("\n\n", $rows);
  };

