    foreach ($packs as $packPosition => $pack) {
      $find = $pdo->prepare('SELECT * FROM homeworks WHERE lesson_id=? AND title=? ORDER BY id');
      $find->execute([$lessonId, $pack['title']]);
      $named = $find->fetchAll();
      if (count($named) > 1) throw new RuntimeException('Найдены дубли ДЗ «' . $pack['title'] . '»');
      $homework = $named[0] ?? null;

      if (!$homework) {
        $blank = $pdo->prepare(
          "SELECT h.* FROM homeworks h
           WHERE h.lesson_id=? AND h.level=?
             AND NOT EXISTS (SELECT 1 FROM questions q WHERE q.homework_id=h.id)
             AND NOT EXISTS (SELECT 1 FROM submissions s WHERE s.homework_id=h.id)
           ORDER BY h.id"
        );
        $blank->execute([$lessonId, $pack['level']]);
        $blanks = $blank->fetchAll();
        if (count($blanks) > 1) throw new RuntimeException('Несколько пустых ДЗ уровня ' . $pack['level']);
        $homework = $blanks[0] ?? null;
      }

      if ($homework) {
        $homeworkId = (int)$homework['id'];
        $questionsSt = $pdo->prepare('SELECT * FROM questions WHERE homework_id=? ORDER BY position,id');
        $questionsSt->execute([$homeworkId]);
        $existing = $questionsSt->fetchAll();
        if ($existing) {
          if ($homework['title'] !== $pack['title'] || $homework['level'] !== $pack['level'] || count($existing) !== count($pack['questions'])) {
            throw new RuntimeException('ДЗ «' . $pack['title'] . '» уже содержит другой контент');
          }
          $ids[] = $homeworkId;
          continue;
        }
        $effectiveDeadline = trim((string)$homework['deadline']) !== '' ? $homework['deadline'] : $deadline;
        $pdo->prepare('UPDATE homeworks SET title=?,level=?,deadline=?,position=? WHERE id=?')
          ->execute([$pack['title'], $pack['level'], $effectiveDeadline, $packPosition, $homeworkId]);
      } else {
        $pdo->prepare('INSERT INTO homeworks(lesson_id,level,title,deadline,position) VALUES(?,?,?,?,?)')
          ->execute([$lessonId, $pack['level'], $pack['title'], $deadline, $packPosition]);
        $homeworkId = (int)$pdo->lastInsertId();
      }

      $insert = $pdo->prepare(
        'INSERT INTO questions(homework_id,type,text,options,correct,solution,hint,points,optional,hard,case_sensitive,grade_mode,file_limit,position)
         VALUES(?,?,?,?,?,?,?,?,0,0,0,?,?,?)'
      );
      foreach ($pack['questions'] as $position => $question) {
        $insert->execute([
          $homeworkId,
          $question['type'],
          $question['text'],
          $json($question['options']),
          $json($question['correct']),
          $question['solution'],
          $question['hint'],
          $question['points'],
          $question['grade_mode'],
          $question['file_limit'],
          $position,
        ]);
      }
      $ids[] = $homeworkId;
    }
    $pdo->commit();
    return $ids;
  } catch (Throwable $e) {
    if ($pdo->inTransaction()) $pdo->rollBack();
    throw $e;
  }
}
