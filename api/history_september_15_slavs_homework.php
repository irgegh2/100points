function history_september_15_slavs_homework_seed(PDO $pdo): int {
  $lessons = $pdo->query(
    "SELECT l.id FROM lessons l
     JOIN blocks b ON b.id=l.block_id JOIN months m ON m.id=b.month_id
     JOIN courses c ON c.id=b.course_id JOIN subjects s ON s.id=c.subject_id
     WHERE s.slug='history' AND c.title='Годовой курс ЕГЭ по истории' AND c.type='Основные'
       AND m.name='БЛОК 1' AND b.n=1 AND b.title='Древняя Русь'
       AND l.title='Восточные славяне в древности' AND l.air_at='2026-09-15 16:00'"
  )->fetchAll(PDO::FETCH_COLUMN);
  if (count($lessons) !== 1) throw new RuntimeException('История, 15 сентября: ожидали ровно один точный урок; найдено ' . count($lessons));
  $lessonId = (int)$lessons[0];
  $title = 'Восточные славяне в древности — задания 1–21';
  $deadline = '2026-09-23 23:59:00'; // семь календарных дней от 16.09.2026, московское время
  $questions = history_september_15_slavs_homework_questions();
  if (count($questions) !== 21) throw new RuntimeException('Ожидается 21 задание');
  $json = static fn($v) => $v === null ? null : json_encode($v, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
  $pdo->beginTransaction();
  try {
    $st = $pdo->prepare('SELECT * FROM homeworks WHERE lesson_id=? AND title=? ORDER BY id');
    $st->execute([$lessonId, $title]);
    $named = $st->fetchAll();
    if (count($named) > 1) throw new RuntimeException('Дубли ДЗ — данные не изменены');
    $hw = $named[0] ?? null;
    if (!$hw) {
      $st = $pdo->prepare("SELECT h.* FROM homeworks h WHERE h.lesson_id=?
        AND (h.level='normal' OR h.level IS NULL OR h.level='')
        AND NOT EXISTS (SELECT 1 FROM questions q WHERE q.homework_id=h.id)
        AND NOT EXISTS (SELECT 1 FROM submissions s WHERE s.homework_id=h.id) ORDER BY h.id");
      $st->execute([$lessonId]);
      $empty = $st->fetchAll();
      if (count($empty) > 1) throw new RuntimeException('Несколько пустых ДЗ — нельзя выбрать произвольно');
      $hw = $empty[0] ?? null;
    }
    if ($hw) {
      $id = (int)$hw['id'];
      $st = $pdo->prepare('SELECT * FROM questions WHERE homework_id=? ORDER BY position,id');
      $st->execute([$id]);
      $existing = $st->fetchAll();
      if ($existing) {
        // Повторный вызов только проверяет совпадение. Даже ручной дедлайн сохраняется.
        if ($hw['title'] !== $title || $hw['level'] !== 'normal' || count($existing) !== count($questions)) {
          throw new RuntimeException('В ДЗ уже есть другой контент — не перезаписываем');
        }
        foreach ($questions as $i => $q) {
          $row = $existing[$i];
          foreach (['type','text','solution','hint','points','grade_mode','file_limit'] as $field) {
            if ((string)$row[$field] !== (string)$q[$field]) throw new RuntimeException('Изменено задание ' . ($i + 1) . ': ' . $field);
          }
          foreach (['options','correct'] as $field) {
            if (($row[$field] === null ? null : json_decode($row[$field], true)) !== $q[$field]) throw new RuntimeException('Изменён ключ или варианты задания ' . ($i + 1));
          }
          if ((int)$row['position'] !== $i || (int)$row['optional'] !== 0 || (int)$row['hard'] !== 0) throw new RuntimeException('Изменены параметры задания');
          $at = $pdo->prepare('SELECT kind,name,size,url FROM question_attachments WHERE question_id=? ORDER BY position,id');
          $at->execute([(int)$row['id']]);
          if ($at->fetchAll(PDO::FETCH_ASSOC) !== $q['attachments']) throw new RuntimeException('Изменены вложения задания ' . ($i + 1));
        }
        $pdo->commit();
        return $id;
      }
      $st = $pdo->prepare('SELECT COUNT(*) FROM submissions WHERE homework_id=?');
      $st->execute([$id]);
      if ((int)$st->fetchColumn() > 0) throw new RuntimeException('В пустом ДЗ уже есть сдачи — не меняем');
      $effectiveDeadline = trim((string)$hw['deadline']) !== '' ? $hw['deadline'] : $deadline;
      $pdo->prepare("UPDATE homeworks SET title=?,level='normal',deadline=? WHERE id=?")
        ->execute([$title, $effectiveDeadline, $id]);
    } else {
      $st = $pdo->prepare('SELECT COALESCE(MAX(position),-1)+1 FROM homeworks WHERE lesson_id=?');
      $st->execute([$lessonId]);
      $pdo->prepare("INSERT INTO homeworks(lesson_id,level,title,deadline,position) VALUES(?,'normal',?,?,?)")
        ->execute([$lessonId,$title,$deadline,(int)$st->fetchColumn()]);
      $id = (int)$pdo->lastInsertId();
    }
    $ins = $pdo->prepare('INSERT INTO questions(homework_id,type,text,options,correct,solution,hint,points,optional,hard,case_sensitive,grade_mode,file_limit,position) VALUES(?,?,?,?,?,?,?,?,0,0,0,?,?,?)');
    $attach = $pdo->prepare('INSERT INTO question_attachments(question_id,kind,name,size,url,position) VALUES(?,?,?,?,?,?)');
    foreach ($questions as $i => $q) {
      $ins->execute([$id,$q['type'],$q['text'],$json($q['options']),$json($q['correct']),$q['solution'],$q['hint'],$q['points'],$q['grade_mode'],$q['file_limit'],$i]);
      $questionId = (int)$pdo->lastInsertId();
      foreach ($q['attachments'] as $pos => $a) $attach->execute([$questionId,$a['kind'],$a['name'],$a['size'],$a['url'],$pos]);
    }
    $pdo->commit();
    return $id;
  } catch (Throwable $e) {
    if ($pdo->inTransaction()) $pdo->rollBack();
    throw $e;
  }
}
