function social_september_25_exam_practice_seed(PDO $pdo): array {
  $lessonSt = $pdo->query(
    "SELECT l.id FROM lessons l
     JOIN blocks b ON b.id=l.block_id
     JOIN months m ON m.id=b.month_id
     JOIN courses c ON c.id=b.course_id
     JOIN subjects s ON s.id=c.subject_id
     WHERE s.slug='social'
       AND c.title='Ликбез ВАЛЕНТИНАЧА 2026/27'
       AND m.name='БЛОК 1'
       AND b.title='Работа с заданиями и экзаменационная практика'
       AND l.title='Как правильно распределить время на экзамене?'
       AND l.air_at='2026-09-25 18:00'"
  );
  $lessons = $lessonSt ? $lessonSt->fetchAll(PDO::FETCH_COLUMN) : [];
  if (count($lessons) !== 1) {
    throw new RuntimeException('Общество, эфир 25 сентября, 18:00: ожидали ровно один точный урок; найдено ' . count($lessons));
  }

  $lessonId = (int)$lessons[0];
  $deadlineSt = $pdo->prepare('SELECT deadline FROM homeworks WHERE lesson_id=? AND level=? ORDER BY position,id LIMIT 1');
  $deadlineSt->execute([$lessonId, 'normal']);
  $deadline = trim((string)$deadlineSt->fetchColumn());
  if ($deadline === '') $deadline = '2026-10-02 23:59:00';
  $packs = social_september_25_exam_practice_packs();
  if (count($packs[0]['questions']) !== 16 || count($packs[1]['questions']) !== 9) {
    throw new RuntimeException('Неверное количество заданий в ДЗ к эфиру 25 сентября');
  }
  $json = static fn($value) => $value === null
    ? null
    : json_encode($value, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);

  $pdo->beginTransaction();
  try {
    $ids = [];
    foreach ($packs as $pack) {
      $find = $pdo->prepare('SELECT * FROM homeworks WHERE lesson_id=? AND title=? ORDER BY id');
      $find->execute([$lessonId, $pack['title']]);
      $named = $find->fetchAll();
      if (count($named) > 1) throw new RuntimeException('Найдены дубли ДЗ «' . $pack['title'] . '»');
      $homework = $named[0] ?? null;

      if (!$homework) {
        $blank = $pdo->prepare(
          "SELECT h.* FROM homeworks h
           WHERE h.lesson_id=? AND h.level=?
             AND NOT EXISTS (SELECT 1 FROM questions q WHERE q.homework_id=h.id)
             AND NOT EXISTS (SELECT 1 FROM submissions s WHERE s.homework_id=h.id)
           ORDER BY h.id"
        );
        $blank->execute([$lessonId, $pack['level']]);
        $blanks = $blank->fetchAll();
        if (count($blanks) > 1) throw new RuntimeException('Несколько пустых ДЗ уровня ' . $pack['level']);
        $homework = $blanks[0] ?? null;
      }

      if ($homework) {
        $homeworkId = (int)$homework['id'];
        $questionsSt = $pdo->prepare('SELECT * FROM questions WHERE homework_id=? ORDER BY position,id');
        $questionsSt->execute([$homeworkId]);
        $existing = $questionsSt->fetchAll();
        if ($existing) {
          if ($homework['title'] !== $pack['title'] || $homework['level'] !== $pack['level'] || count($existing) !== count($pack['questions'])) {
            throw new RuntimeException('ДЗ «' . $pack['title'] . '» уже содержит другой контент');
          }
          foreach ($pack['questions'] as $position => $question) {
            $row = $existing[$position];
            foreach (['type', 'text', 'solution', 'hint', 'points', 'grade_mode', 'file_limit'] as $field) {
              if ((string)$row[$field] !== (string)$question[$field]) {
                throw new RuntimeException('ДЗ уже содержит другой контент: ' . $field);
              }
            }
            foreach (['options', 'correct'] as $field) {
              $stored = $row[$field] === null ? null : json_decode($row[$field], true, 512, JSON_THROW_ON_ERROR);
              if ($stored !== $question[$field]) throw new RuntimeException('ДЗ уже содержит другие ответы');
            }
          }
          $ids[] = $homeworkId;
          continue;
        }
        $submissionSt = $pdo->prepare('SELECT COUNT(*) FROM submissions WHERE homework_id=?');
        $submissionSt->execute([$homeworkId]);
        if ((int)$submissionSt->fetchColumn() > 0) throw new RuntimeException('Нельзя изменять ДЗ с работами учеников');
        $effectiveDeadline = trim((string)$homework['deadline']) !== '' ? $homework['deadline'] : $deadline;
        $pdo->prepare('UPDATE homeworks SET title=?,level=?,deadline=? WHERE id=?')
          ->execute([$pack['title'], $pack['level'], $effectiveDeadline, $homeworkId]);
      } else {
        $positionSt = $pdo->prepare('SELECT COALESCE(MAX(position),-1)+1 FROM homeworks WHERE lesson_id=?');
        $positionSt->execute([$lessonId]);
        $pdo->prepare('INSERT INTO homeworks(lesson_id,level,title,deadline,position) VALUES(?,?,?,?,?)')
          ->execute([$lessonId, $pack['level'], $pack['title'], $deadline, (int)$positionSt->fetchColumn()]);
        $homeworkId = (int)$pdo->lastInsertId();
      }

      $insert = $pdo->prepare(
        'INSERT INTO questions(homework_id,type,text,options,correct,solution,hint,points,optional,hard,case_sensitive,grade_mode,file_limit,position)
         VALUES(?,?,?,?,?,?,?,?,0,0,0,?,?,?)'
      );
      foreach ($pack['questions'] as $position => $question) {
        $insert->execute([
          $homeworkId,
          $question['type'],
          $question['text'],
          $json($question['options']),
          $json($question['correct']),
          $question['solution'],
          $question['hint'],
          $question['points'],
          $question['grade_mode'],
          $question['file_limit'],
          $position,
        ]);
      }
      $ids[] = $homeworkId;
    }
    $pdo->commit();
    return $ids;
  } catch (Throwable $e) {
    if ($pdo->inTransaction()) $pdo->rollBack();
    throw $e;
  }
}
