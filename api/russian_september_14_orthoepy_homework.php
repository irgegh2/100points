function russian_september_14_orthoepy_answer_variants(string $answer): array {
  $permutations = [''];
  foreach (str_split($answer) as $digit) {
    $next = [];
    foreach ($permutations as $prefix) {
      for ($i = 0; $i <= strlen($prefix); $i++) {
        $next[] = substr($prefix, 0, $i) . $digit . substr($prefix, $i);
      }
    }
    $permutations = array_values(array_unique($next));
  }
  $variants = [];
  foreach ($permutations as $digits) {
    $parts = str_split($digits);
    $variants[] = $digits;
    $variants[] = implode(' ', $parts);
    $variants[] = implode(',', $parts);
    $variants[] = implode(';', $parts);
  }
  return array_values(array_unique($variants));
}

