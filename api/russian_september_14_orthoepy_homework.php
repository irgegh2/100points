  $questions = [];
  foreach (russian_september_14_orthoepy_homework_data() as $index => [$words, $answer, $fixes]) {
    $numbered = [];
    foreach ($words as $i => $word) $numbered[] = ($i + 1) . ') ' . $word;
    $correctWords = [];
    foreach (str_split($answer) as $digit) $correctWords[] = $digit . ') ' . $words[(int)$digit - 1];
    $text = '**№ ' . ($index + 1) . '.** ' . $lead . "\n\n" . implode("\n\n", $numbered);
    $solution = '**Ответ:** ' . $answer . ".\n\n**Верное ударение:** " . implode(', ', $correctWords)
      . ".\n\n**Ошибочные варианты — как правильно:** " . implode(', ', $fixes) . '.';
    $questions[] = [$text, russian_september_14_orthoepy_answer_variants($answer), $solution];
  }
  return $questions;
}
